def caps_width(text, xh, track=0.12):
    return word_width(text, xh, track)


def draw_text(ink, name, x, y_base, text, xh, width, tone=255, track=0.12):
    """Draw `text` (any glyph in GLYPHS; others advance as a gap) with the left edge at x."""
    return print_word(ink, name, x, y_base, text, xh, width, np.random.default_rng(0), tone, 0.0, 0.0, track)
